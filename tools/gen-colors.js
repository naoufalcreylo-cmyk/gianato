// Generates theme/snippets/color-siblings.liquid from prototype/data/catalog.json:
// the colour map of the catalogue (each colour = its own product), used until the gianato.* metafields are imported.
// node tools/gen-colors.js   (re-run after tools/build-catalog.js when products change)
// Params: product, mode ('model' | 'colorway' | 'card' | 'pdp'), max (card), class (card)
const fs = require('fs'), path = require('path');
const C = require('../prototype/data/catalog.json');
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
const fam = {}; C.products.forEach(p => (fam[p.model] = fam[p.model] || []).push(p));
const thumb = p => (p.imgs.find(i => !/\/products\/(DSC|CLD)/.test(i[0])) || p.imgs[0] || [''])[0];
const href = h => `{{ routes.root_url }}products/${h}`;
const cur = h => `{% if product.handle == '${h}' %}`;

const names = C.products.map(p => `  {%- when '${p.h}' -%}{%- if mode == 'model' -%}${esc(p.model)}{%- else -%}${esc(p.cw)}{%- endif -%}`).join('\n');

const families = Object.values(fam).filter(v => v.length > 1).map(v => {
  const handles = v.map(p => `'${p.h}'`).join(', ');
  const n = v.length;
  const dots = v.map((p, i) => `{%- if ${i} < max -%}<a class="swatch${cur(p.h)} is-current{% endif %}" style="--sw: ${p.swatch}" href="${href(p.h)}" title="${esc(p.cw)}" aria-label="${esc(p.model)}, ${esc(p.cw)}"${cur(p.h)} aria-current="true"{% endif %}></a>{%- endif -%}`).join('');
  const thumbs = v.map(p => `<a class="pdp-swatch" href="${href(p.h)}"${cur(p.h)} aria-current="true"{% endif %} title="${esc(p.cw)}" aria-label="${esc(p.model)} ${esc(p.cw)}${p.available ? '' : ' (épuisé)'}"><img src="${thumb(p)}?width=180" alt="" width="180" height="206" loading="lazy" decoding="async"><span class="swatch" style="--sw: ${p.swatch}"></span></a>`).join('');
  return `  {%- when ${handles} -%}
    {%- if mode == 'card' -%}
      <div class="{{ class | default: 'card__swatches' }}" aria-label="${n} couleurs">${dots}{%- if ${n} > max -%}<span class="more">+{{ ${n} | minus: max }}</span>{%- endif -%}</div>
    {%- elsif mode == 'pdp' -%}
      <div class="pdp__block">
        <div class="pdp__block-head"><p class="label">{{ 'product.color' | t }}<strong>{% render 'color-siblings', product: product, mode: 'colorway' %}</strong></p><span class="label muted">${n} couleurs</span></div>
        <div class="pdp-swatches">${thumbs}</div>
      </div>
    {%- endif -%}`;
}).join('\n');

const out = `{%- comment -%}
  Colour map — GENERATED by tools/gen-colors.js from the gianato.ma catalogue (${C.products.length} products, ${Object.keys(fam).length} models).
  Each colour is its own product; clicking a colour opens that product. Used as a fallback while the
  gianato.* metafields (model, colorway, siblings, swatch) are not imported. Do not edit by hand.
{%- endcomment -%}
{% # theme-check-disable LiquidComplexity %}
{%- liquid
  assign max = max | default: 5
-%}
{%- if mode == 'model' or mode == 'colorway' -%}
{%- case product.handle -%}
${names}
{%- endcase -%}
{%- else -%}
{%- case product.handle -%}
${families}
{%- endcase -%}
{%- endif -%}
`;
fs.writeFileSync(path.join(__dirname, '../theme/snippets/color-siblings.liquid'), out);
console.log('color-siblings.liquid', Math.round(out.length / 1024) + ' KB —', Object.values(fam).filter(v => v.length > 1).length, 'modèles multi-couleurs');
