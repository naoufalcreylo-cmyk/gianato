// Generates theme/snippets/nav-maison.liquid — the built-in « Maison » navigation (header, mega menus, mobile, footer)
// from prototype/data/site.js, so the theme shows the designed menus without any Shopify menu to configure.
// node tools/gen-nav.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const ctx = { window: {} }; vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../prototype/data/site.js'), 'utf8'), ctx);
const S = ctx.window.GIANATO_SITE;
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

// Prototype href → store URL (Liquid). maison_url / service_url are resolved at render time (theme settings, with fallbacks).
const url = h => {
  if (/^https?:/.test(h)) return h.replace('https://gianato.ma', '');
  const [file, hash] = h.split('#'); const a = hash ? `#${hash}` : '';
  if (file === 'maison.html') return `{{ maison_url }}${a}`;
  if (file === 'service.html') return `{{ service_url }}${a}`;
  const c = file.match(/collection\.html\?c=(.+)/); if (c) return `{{ routes.collections_url }}/${c[1]}${a}`;
  const p = file.match(/product\.html\?p=(.+)/); if (p) return `/products/${p[1]}${a}`;
  if (!file.includes('.html')) return `{{ routes.collections_url }}/${file}`; // bare collection handle (mega columns)
  return h;
};

const left = S.nav.filter(n => !n.end), right = S.nav.filter(n => n.end);
const item = n => n.mega
  ? `<button class="nav-link" type="button" aria-expanded="false" aria-controls="mega-${n.mega}" data-mega-trigger="${n.mega}">${esc(n.title)}</button>`
  : `<a class="nav-link${n.sale ? ' nav-link--sale' : ''}" href="${url(n.href)}">${esc(n.title)}</a>`;

const mega = n => {
  const m = S.mega[n.mega];
  return `<div class="mega" id="mega-${n.mega}" data-mega="${n.mega}" aria-hidden="true">
  <div class="container mega__inner">
    <div class="mega__cols">
${m.columns.map(c => `      <div class="mega__col"><h3>${esc(c.title)}</h3><ul role="list">${c.links.map(([t, h]) => `<li><a href="${url(h)}">${esc(t)}</a></li>`).join('')}</ul></div>`).join('\n')}
      <div class="mega__aside">
        ${m.all ? `<a class="link" href="${url(m.all[1])}">${esc(m.all[0])} {% render 'icon', name: 'arrow' %}</a>` : '<span></span>'}
        ${m.quiet ? `<a class="mega__quiet" href="${url(m.quiet[1])}">${esc(m.quiet[0])}</a>` : ''}
      </div>
    </div>
    {%- assign feature = nil -%}{%- for b in blocks -%}{%- if b.settings.menu_item == ${JSON.stringify(n.title)} -%}{%- assign feature = b -%}{%- endif -%}{%- endfor -%}
    {%- if feature -%}
      {%- capture fallback_url -%}${url(m.feature.href)}{%- endcapture -%}
      <a class="mega__feature" href="{{ feature.settings.url | default: fallback_url }}" {{ feature.shopify_attributes }}>
        <div class="media">{% render 'image', image: feature.settings.image, fallback: feature.settings.fallback, sizes: '22vw', alt: '', max: 960 %}</div>
        <div><p class="eyebrow eyebrow--plain">{{ feature.settings.kicker }}</p><p class="h4" style="color:var(--heading);margin-top:.75rem">{{ feature.settings.title }}</p><p>{{ feature.settings.text }}</p><span class="link" style="margin-top:1.25rem">{{ 'general.discover' | t }} {% render 'icon', name: 'arrow' %}</span></div>
      </a>
    {%- endif -%}
  </div>
</div>`;
};

const mobile = S.nav.map(n => n.mega ? `<li><details><summary>${esc(n.title)}{% render 'icon', name: 'plus' %}</summary><div class="mnav__sub">${S.mega[n.mega].columns.map(c => `<div><h3>${esc(c.title)}</h3><ul role="list">${c.links.map(([t, h]) => `<li><a href="${url(h)}">${esc(t)}</a></li>`).join('')}</ul></div>`).join('')}${S.mega[n.mega].quiet ? `<a class="muted" href="${url(S.mega[n.mega].quiet[1])}" style="font-size:var(--fs-sm)">${esc(S.mega[n.mega].quiet[0])}</a>` : ''}</div></details></li>`
  : `<li><a href="${url(n.href)}"${n.sale ? ' class="is-sale"' : ''}>${esc(n.title)}</a></li>`).join('\n');

const footer = S.footer.map(c => `<nav class="footer__col" aria-label="${esc(c.title)}"><h2>${esc(c.title)}</h2><ul role="list">${c.links.map(([t, h]) => `<li><a href="${url(h)}">${esc(t)}</a></li>`).join('')}</ul></nav>`).join('\n');
const legal = S.legal.map(([t, h]) => `<li><a href="${url(h)}">${esc(t)}</a></li>`).join('');

const out = `{%- comment -%}
  Built-in « Maison » navigation — GENERATED by tools/gen-nav.js from prototype/data/site.js. Do not edit by hand.
  Params: part ('left' | 'right' | 'megas' | 'mobile' | 'footer' | 'legal'), blocks (header section blocks, for mega visuals).
  maison_url / service_url: theme settings « Page La Maison » / « Page Service client », with fallbacks on existing pages.
{%- endcomment -%}
{%- liquid
  assign maison_url = '/pages/cordonnerie?view=maison'
  if settings.maison_page != blank
    assign maison_url = settings.maison_page.url
  endif
  assign service_url = '/pages/contact?view=service'
  if settings.service_page != blank
    assign service_url = settings.service_page.url
  endif
-%}
{%- case part -%}
  {%- when 'left' -%}
${left.map(n => `<li>${item(n)}</li>`).join('\n')}
  {%- when 'right' -%}
${right.map(n => `<span class="header__end hide-m">${item(n)}</span>`).join('\n')}
  {%- when 'megas' -%}
${S.nav.filter(n => n.mega).map(mega).join('\n')}
  {%- when 'mobile' -%}
${mobile}
  {%- when 'footer' -%}
${footer}
  {%- when 'legal' -%}
${legal}
{%- endcase -%}
`;
fs.writeFileSync(path.join(__dirname, '../theme/snippets/nav-maison.liquid'), out);
console.log('nav-maison.liquid', out.length, 'bytes —', S.nav.length, 'top items,', S.footer.length, 'footer columns');
